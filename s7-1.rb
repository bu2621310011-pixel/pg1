# 数字
## 整数
puts 3

# 浮動小数点数
puts 3.5

# 文字列
# ダブルクォーテーション
puts "Hello, world"

## シングルクォーテーション
puts 'Hello, world'

# 文字列は、どちらでくくっても内容は同じ
puts "Hello, world" == 'Hello, world'

# 英数字記号日本語など、どんな内容でも保持できる
# ただし、バックスラッシュ \ だけは特別な意味がある

# ダブルクォーテーション自身を保持する文字列
puts "\""

# シングルクォーテーション自身を保持する文字列
puts '\''